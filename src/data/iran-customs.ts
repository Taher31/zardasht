/**
 * Names and copy for the Iran customs map.
 *
 * The geometry (outline, marker positions, neighbour label anchors) lives in
 * the generated `iran-map.ts`; this file holds only what a human writes - the
 * name of each post, what it serves, and the surrounding copy, per language.
 * Keys match the `id` values in the generated points array, so adding a post
 * to `scripts/build-iran-map.cjs` means adding a name and a `serves` line here
 * in all four languages.
 */
export type CustomsKind = 'sea' | 'land' | 'air';

export interface CustomsPack {
  eyebrow: string;
  title: string;
  intro: string;
  /** Marker-type legend, which doubles as the filter. */
  kinds: Record<CustomsKind, string>;
  /** Bodies of water labelled on the map. */
  water: { persianGulf: string; gulfOfOman: string; caspian: string };
  /** Labels under the three figures above the map. */
  stats: { posts: string; neighbours: string; coasts: string };
  filterAll: string;
  search: string;
  empty: string;
  hint: string;
  /** Neighbouring country names drawn onto the map. */
  neighbours: Record<string, string>;
  /** Post id -> display name. */
  names: Record<string, string>;
  /** Post id -> the border it serves, shown under the name in the list. */
  serves: Record<string, string>;
  listTitle: string;
  note: string;
}

